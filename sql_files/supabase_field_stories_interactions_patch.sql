DROP POLICY IF EXISTS "Allow public update on field_stories" ON public.field_stories;
DROP POLICY IF EXISTS "Allow public delete on field_stories" ON public.field_stories;
DROP POLICY IF EXISTS "Allow authenticated select on field_stories" ON public.field_stories;
DROP POLICY IF EXISTS "Allow authenticated insert on field_stories" ON public.field_stories;
DROP POLICY IF EXISTS "Allow authenticated update on field_stories" ON public.field_stories;
DROP POLICY IF EXISTS "Allow authenticated delete on field_stories" ON public.field_stories;

CREATE POLICY "Allow public select on field_stories" ON public.field_stories
    FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "Allow authenticated insert on field_stories" ON public.field_stories
    FOR INSERT TO authenticated WITH CHECK (true);
CREATE POLICY "Allow authenticated update on field_stories" ON public.field_stories
    FOR UPDATE TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "Allow authenticated delete on field_stories" ON public.field_stories
    FOR DELETE TO authenticated USING (true);

REVOKE ALL PRIVILEGES ON TABLE public.field_stories FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.field_stories TO anon, authenticated;
GRANT INSERT (
    id, category, category_label_id, category_label_en, read_time_id, read_time_en,
    date_id, date_en, author_name, author_role_id, author_role_en, author_avatar,
    image, title_id, title_en, excerpt_id, excerpt_en, quote_id, quote_en,
    content_id, content_en
) ON TABLE public.field_stories TO authenticated;
GRANT UPDATE (
    id, category, category_label_id, category_label_en, read_time_id, read_time_en,
    date_id, date_en, author_name, author_role_id, author_role_en, author_avatar,
    image, title_id, title_en, excerpt_id, excerpt_en, quote_id, quote_en,
    content_id, content_en
) ON TABLE public.field_stories TO authenticated;
GRANT DELETE ON TABLE public.field_stories TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.field_stories_id_seq TO authenticated;

REVOKE ALL PRIVILEGES ON TABLE public.story_reactions FROM PUBLIC, anon, authenticated;
REVOKE ALL PRIVILEGES ON TABLE public.story_comments FROM PUBLIC, anon, authenticated;
GRANT SELECT (id, story_id, author_name, comment_text, is_approved, created_at)
    ON TABLE public.story_comments TO anon, authenticated;

CREATE OR REPLACE FUNCTION public.get_story_interaction_state(
    p_story_id bigint,
    p_client_fingerprint uuid
)
RETURNS TABLE (
    claps_count integer,
    loves_count integer,
    claps_used integer,
    loved boolean
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
    SELECT
        COALESCE(s.claps_count, 0)::integer,
        COALESCE(s.loves_count, 0)::integer,
        COUNT(r.id) FILTER (WHERE r.reaction_type = 'clap')::integer,
        COALESCE(bool_or(r.reaction_type = 'love'), false)
    FROM public.field_stories AS s
    LEFT JOIN public.story_reactions AS r
        ON r.story_id = s.id
       AND r.client_fingerprint = p_client_fingerprint
    WHERE s.id = p_story_id
    GROUP BY s.id;
$function$;

CREATE OR REPLACE FUNCTION public.increment_story_claps(
    p_story_id bigint,
    p_client_fingerprint uuid,
    p_request_id uuid
)
RETURNS TABLE (
    status text,
    claps_count integer,
    claps_used integer
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
DECLARE
    v_claps_count integer;
    v_claps_used integer;
BEGIN
    IF p_story_id IS NULL OR p_client_fingerprint IS NULL OR p_request_id IS NULL THEN
        RAISE EXCEPTION 'A story, client, and request ID are required.'
            USING ERRCODE = '22023';
    END IF;

    SELECT COALESCE(s.claps_count, 0)::integer
    INTO v_claps_count
    FROM public.field_stories AS s
    WHERE s.id = p_story_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RETURN QUERY SELECT 'not_found'::text, 0, 0;
        RETURN;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM public.story_reactions AS r
        WHERE r.story_id = p_story_id
          AND r.client_fingerprint = p_client_fingerprint
          AND r.request_id = p_request_id
    ) THEN
        SELECT COUNT(*)::integer
        INTO v_claps_used
        FROM public.story_reactions AS r
        WHERE r.story_id = p_story_id
          AND r.client_fingerprint = p_client_fingerprint
          AND r.reaction_type = 'clap';

        RETURN QUERY SELECT 'recorded'::text, v_claps_count, v_claps_used;
        RETURN;
    END IF;

    SELECT COUNT(*)::integer
    INTO v_claps_used
    FROM public.story_reactions AS r
    WHERE r.story_id = p_story_id
      AND r.client_fingerprint = p_client_fingerprint
      AND r.reaction_type = 'clap';

    IF v_claps_used >= 50 THEN
        RETURN QUERY SELECT 'limit_reached'::text, v_claps_count, v_claps_used;
        RETURN;
    END IF;

    INSERT INTO public.story_reactions (
        story_id, reaction_type, client_fingerprint, request_id
    ) VALUES (
        p_story_id, 'clap', p_client_fingerprint, p_request_id
    );

    UPDATE public.field_stories AS s
    SET claps_count = COALESCE(s.claps_count, 0) + 1
    WHERE s.id = p_story_id
    RETURNING s.claps_count INTO v_claps_count;

    v_claps_used := v_claps_used + 1;
    RETURN QUERY SELECT 'recorded'::text, v_claps_count, v_claps_used;
END;
$function$;

CREATE OR REPLACE FUNCTION public.record_story_love(
    p_story_id bigint,
    p_client_fingerprint uuid
)
RETURNS TABLE (
    status text,
    loves_count integer,
    loved boolean
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
DECLARE
    v_loves_count integer;
BEGIN
    IF p_story_id IS NULL OR p_client_fingerprint IS NULL THEN
        RAISE EXCEPTION 'A story and client ID are required.'
            USING ERRCODE = '22023';
    END IF;

    SELECT COALESCE(s.loves_count, 0)::integer
    INTO v_loves_count
    FROM public.field_stories AS s
    WHERE s.id = p_story_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RETURN QUERY SELECT 'not_found'::text, 0, false;
        RETURN;
    END IF;

    INSERT INTO public.story_reactions (
        story_id, reaction_type, client_fingerprint, request_id
    ) VALUES (
        p_story_id, 'love', p_client_fingerprint, NULL
    )
    ON CONFLICT (story_id, client_fingerprint) WHERE reaction_type = 'love'
    DO NOTHING;

    IF FOUND THEN
        UPDATE public.field_stories AS s
        SET loves_count = COALESCE(s.loves_count, 0) + 1
        WHERE s.id = p_story_id
        RETURNING s.loves_count INTO v_loves_count;
        RETURN QUERY SELECT 'loved'::text, v_loves_count, true;
        RETURN;
    END IF;

    RETURN QUERY SELECT 'already_loved'::text, v_loves_count, true;
END;
$function$;

CREATE OR REPLACE FUNCTION public.submit_story_comment(
    p_story_id bigint,
    p_author_name text,
    p_comment_text text
)
RETURNS TABLE (status text)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
DECLARE
    v_author_name text := btrim(COALESCE(p_author_name, ''));
    v_comment_text text := btrim(COALESCE(p_comment_text, ''));
BEGIN
    IF p_story_id IS NULL THEN
        RAISE EXCEPTION 'A story ID is required.' USING ERRCODE = '22023';
    END IF;
    IF char_length(v_author_name) = 0 OR char_length(v_author_name) > 80 THEN
        RAISE EXCEPTION 'Name must contain 1 to 80 characters.' USING ERRCODE = '22023';
    END IF;
    IF char_length(v_comment_text) = 0 OR char_length(v_comment_text) > 1000 THEN
        RAISE EXCEPTION 'Comment must contain 1 to 1000 characters.' USING ERRCODE = '22023';
    END IF;
    IF v_comment_text ~* '(^|[^[:alnum:]])f[[:space:][:punct:]]{0,2}u[[:space:][:punct:]]{0,2}c[[:space:][:punct:]]{0,2}k($|[^[:alnum:]])'
       OR v_comment_text ~* '(^|[^[:alnum:]])s[[:space:][:punct:]]{0,2}h[[:space:][:punct:]]{0,2}i[[:space:][:punct:]]{0,2}t($|[^[:alnum:]])'
       OR v_comment_text ~* '(^|[^[:alnum:]])b[[:space:][:punct:]]{0,2}i[[:space:][:punct:]]{0,2}t[[:space:][:punct:]]{0,2}c[[:space:][:punct:]]{0,2}h($|[^[:alnum:]])'
       OR v_comment_text ~* '(^|[^[:alnum:]])a[[:space:][:punct:]]{0,2}s[[:space:][:punct:]]{0,2}s[[:space:][:punct:]]{0,2}h[[:space:][:punct:]]{0,2}o[[:space:][:punct:]]{0,2}l[[:space:][:punct:]]{0,2}e($|[^[:alnum:]])'
       OR v_comment_text ~* '(^|[^[:alnum:]])b[[:space:][:punct:]]{0,2}a[[:space:][:punct:]]{0,2}j[[:space:][:punct:]]{0,2}i[[:space:][:punct:]]{0,2}n[[:space:][:punct:]]{0,2}g[[:space:][:punct:]]{0,2}a[[:space:][:punct:]]{0,2}n($|[^[:alnum:]])'
       OR v_comment_text ~* '(^|[^[:alnum:]])k[[:space:][:punct:]]{0,2}o[[:space:][:punct:]]{0,2}n[[:space:][:punct:]]{0,2}t[[:space:][:punct:]]{0,2}o[[:space:][:punct:]]{0,2}l($|[^[:alnum:]])'
       OR v_comment_text ~* '(^|[^[:alnum:]])m[[:space:][:punct:]]{0,2}e[[:space:][:punct:]]{0,2}m[[:space:][:punct:]]{0,2}e[[:space:][:punct:]]{0,2}k($|[^[:alnum:]])'
       OR v_comment_text ~* '(^|[^[:alnum:]])n[[:space:][:punct:]]{0,2}g[[:space:][:punct:]]{0,2}e[[:space:][:punct:]]{0,2}n[[:space:][:punct:]]{0,2}t[[:space:][:punct:]]{0,2}o[[:space:][:punct:]]{0,2}t($|[^[:alnum:]])' THEN
        RAISE EXCEPTION 'Comment contains language that is not allowed.' USING ERRCODE = '22023';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM public.field_stories AS s WHERE s.id = p_story_id
    ) THEN
        RAISE EXCEPTION 'Story not found.' USING ERRCODE = '23503';
    END IF;

    INSERT INTO public.story_comments (story_id, author_name, comment_text, is_approved)
    VALUES (p_story_id, v_author_name, v_comment_text, false);

    RETURN QUERY SELECT 'submitted'::text;
END;
$function$;

