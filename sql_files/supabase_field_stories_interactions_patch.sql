-- Apply sql_files/supabase_field_stories_patch.sql first.
-- This script is based on the repository schema; it has not been applied to Supabase.

BEGIN;

ALTER TABLE public.field_stories
    ADD COLUMN IF NOT EXISTS claps_count integer NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS loves_count integer NOT NULL DEFAULT 0;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'public.field_stories'::regclass
          AND conname = 'field_stories_interaction_counts_nonnegative'
    ) THEN
        ALTER TABLE public.field_stories
            ADD CONSTRAINT field_stories_interaction_counts_nonnegative
            CHECK (claps_count >= 0 AND loves_count >= 0);
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS public.story_reactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    story_id bigint NOT NULL REFERENCES public.field_stories(id) ON DELETE CASCADE,
    reaction_type text NOT NULL CHECK (reaction_type IN ('clap', 'love')),
    client_fingerprint uuid NOT NULL,
    request_id uuid,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT story_reactions_request_shape CHECK (
        (reaction_type = 'clap' AND request_id IS NOT NULL)
        OR (reaction_type = 'love' AND request_id IS NULL)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS story_reactions_clap_request_unique
    ON public.story_reactions (story_id, client_fingerprint, request_id)
    WHERE reaction_type = 'clap';

CREATE UNIQUE INDEX IF NOT EXISTS story_reactions_single_love_unique
    ON public.story_reactions (story_id, client_fingerprint)
    WHERE reaction_type = 'love';

CREATE TABLE IF NOT EXISTS public.story_comments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    story_id bigint NOT NULL REFERENCES public.field_stories(id) ON DELETE CASCADE,
    author_name varchar(80) NOT NULL,
    comment_text varchar(1000) NOT NULL,
    is_approved boolean NOT NULL DEFAULT false,
    created_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS story_comments_story_approval_date_idx
    ON public.story_comments (story_id, is_approved, created_at, id);

ALTER TABLE public.story_reactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.story_comments ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public read approved story comments" ON public.story_comments;
CREATE POLICY "Public read approved story comments" ON public.story_comments
    FOR SELECT TO anon, authenticated
    USING (is_approved IS TRUE);
-- Pending reads and approval updates stay unavailable to authenticated users until a trusted moderator role exists.

-- Replace the source patch's broad public write policies and prevent direct counter edits.
DROP POLICY IF EXISTS "Allow public select on field_stories" ON public.field_stories;
