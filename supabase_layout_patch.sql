-- 2. Certificate Settings Table (Re-creation supporting multiple events)
DROP TABLE IF EXISTS public.certificate_settings CASCADE;

CREATE TABLE public.certificate_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name VARCHAR(255) UNIQUE NOT NULL,
    template_image TEXT,
    layout_json JSONB,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Enable RLS
ALTER TABLE public.certificate_settings ENABLE ROW LEVEL SECURITY;

-- Policies for Certificate Settings
DROP POLICY IF EXISTS "Allow public select on certificate_settings" ON public.certificate_settings;
CREATE POLICY "Allow public select on certificate_settings" ON public.certificate_settings FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow admin all on certificate_settings" ON public.certificate_settings;
CREATE POLICY "Allow admin all on certificate_settings" ON public.certificate_settings FOR ALL TO authenticated USING (true);

