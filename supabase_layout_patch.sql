-- 1. Events Table (To hold dynamic event data)
CREATE TABLE IF NOT EXISTS public.events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title_id VARCHAR(255) NOT NULL,
    title_en VARCHAR(255),
    date VARCHAR(100) NOT NULL,
    time VARCHAR(100),
    location VARCHAR(255),
    description_id TEXT,
    description_en TEXT,
    speaker VARCHAR(255),
    speaker_role VARCHAR(255),
    image TEXT,
    link TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Enable RLS for Events
ALTER TABLE public.events ENABLE ROW LEVEL SECURITY;

-- Events Policies
DROP POLICY IF EXISTS "Allow public select on events" ON public.events;
CREATE POLICY "Allow public select on events" ON public.events FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow admin all on events" ON public.events;
CREATE POLICY "Allow admin all on events" ON public.events FOR ALL TO authenticated USING (true);

